function regionOf(id) {
  return id.startsWith("cn-")
    ? "china"
    : id.startsWith("us-")
      ? "united-states"
      : id.startsWith("eu-")
        ? "europe"
        : id.startsWith("jp-")
          ? "japan"
          : "hong-kong";
}

